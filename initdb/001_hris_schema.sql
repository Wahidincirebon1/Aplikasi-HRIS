BEGIN;

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE CHECK (btrim(email) <> ''),
    password TEXT NOT NULL,
    name TEXT NOT NULL DEFAULT '',
    role TEXT NOT NULL DEFAULT 'employee'
        CHECK (role IN ('superadmin', 'admin', 'employee')),
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('pending', 'active', 'inactive')),
    nik TEXT UNIQUE,
    address TEXT NOT NULL DEFAULT '',
    no_tlp TEXT NOT NULL DEFAULT '',
    division TEXT NOT NULL DEFAULT '',
    position TEXT NOT NULL DEFAULT '',
    birth_date DATE,
    photo TEXT NOT NULL DEFAULT '',
    grade TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS attendances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL DEFAULT '',
    nik TEXT NOT NULL DEFAULT '',
    division TEXT NOT NULL DEFAULT '',
    position TEXT NOT NULL DEFAULT '',
    grade TEXT NOT NULL DEFAULT '',
    role TEXT NOT NULL DEFAULT '',
    tanggal DATE NOT NULL,
    jam_masuk TIME,
    jam_pulang TIME,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, tanggal)
);

CREATE TABLE IF NOT EXISTS absensi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    tanggal DATE NOT NULL,
    jam_masuk TIME,
    jam_pulang TIME,
    status TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, tanggal)
);

CREATE TABLE IF NOT EXISTS cuti (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    tanggal_mulai DATE NOT NULL,
    tanggal_selesai DATE NOT NULL,
    alasan TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (tanggal_selesai >= tanggal_mulai)
);

CREATE TABLE IF NOT EXISTS izin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    nik TEXT NOT NULL DEFAULT '',
    division TEXT NOT NULL DEFAULT '',
    position TEXT NOT NULL DEFAULT '',
    grade TEXT NOT NULL DEFAULT '',
    permission TEXT NOT NULL,
    tanggal DATE NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS lembur (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL DEFAULT '',
    name TEXT NOT NULL DEFAULT '',
    nik TEXT NOT NULL DEFAULT '',
    division TEXT NOT NULL DEFAULT '',
    position TEXT NOT NULL DEFAULT '',
    grade TEXT NOT NULL DEFAULT '',
    overtime TEXT NOT NULL DEFAULT '',
    date DATE NOT NULL,
    start_time TIME NOT NULL,
    finish_time TIME NOT NULL,
    total_overtime TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (finish_time >= start_time)
);

CREATE TABLE IF NOT EXISTS other_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    name TEXT NOT NULL DEFAULT '',
    nik TEXT NOT NULL DEFAULT '',
    division TEXT NOT NULL DEFAULT '',
    position TEXT NOT NULL DEFAULT '',
    grade TEXT NOT NULL DEFAULT '',
    reason TEXT NOT NULL,
    date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    total_duration TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (end_time >= start_time)
);

CREATE TABLE IF NOT EXISTS logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_email TEXT NOT NULL DEFAULT '',
    action TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE INDEX IF NOT EXISTS idx_attendances_tanggal
    ON attendances (tanggal DESC);
CREATE INDEX IF NOT EXISTS idx_absensi_tanggal
    ON absensi (tanggal DESC);
CREATE INDEX IF NOT EXISTS idx_cuti_user_tanggal
    ON cuti (user_id, tanggal_mulai DESC);
CREATE INDEX IF NOT EXISTS idx_cuti_status_tanggal
    ON cuti (status, tanggal_mulai DESC);
CREATE INDEX IF NOT EXISTS idx_izin_created_at
    ON izin (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_izin_status_created_at
    ON izin (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_lembur_date
    ON lembur (date DESC);
CREATE INDEX IF NOT EXISTS idx_other_requests_employee_date
    ON other_requests (employee_id, date DESC);
CREATE INDEX IF NOT EXISTS idx_logs_user_created_at
    ON logs (user_email, created_at DESC);

COMMIT;
